CREATE TABLE RECONCILIATION_RUN
(
    RUN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    BUSINESS_DATE DATE NOT NULL,

    START_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    END_TIME TIMESTAMP,

    STATUS VARCHAR2(20),

    CREATED_BY VARCHAR2(50),

    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--------------------------------------------------------

CREATE TABLE DEPOSIT_SUMMARY
(
    SUMMARY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    BUSINESS_DATE DATE,

    SOURCE_SYSTEM VARCHAR2(30),

    TOTAL_DEPOSIT NUMBER(18,2),

    RETAIL_DEPOSIT NUMBER(18,2),

    SEGMENTATION_DEPOSIT NUMBER(18,2),

    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--------------------------------------------------------

CREATE TABLE SEGMENT_DEPOSIT
(
    SEGMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    BUSINESS_DATE DATE,

    SOURCE_SYSTEM VARCHAR2(30),

    SEGMENT_NAME VARCHAR2(50),

    AMOUNT NUMBER(18,2),

    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

--------------------------------------------------------

CREATE TABLE RECONCILIATION_RESULT
(
    RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    RUN_ID NUMBER,

    RULE_NAME VARCHAR2(100),

    STATUS VARCHAR2(20),

    EXPECTED_VALUE NUMBER(18,2),

    ACTUAL_VALUE NUMBER(18,2),

    DIFFERENCE NUMBER(18,2),

    MESSAGE VARCHAR2(500),

    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_RESULT_RUN
    FOREIGN KEY(RUN_ID)
    REFERENCES RECONCILIATION_RUN(RUN_ID)
);